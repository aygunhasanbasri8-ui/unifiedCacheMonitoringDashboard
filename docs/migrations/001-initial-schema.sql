-- ── İzlenecek instance kayıtları ────────────────────────────────────────────
-- Parola BURADA SAKLANMAZ. password_env_var yalnızca parolanın okunacağı
-- environment değişkeninin ADINI taşır, parolanın kendisi DB'ye yazılmaz.
CREATE TABLE IF NOT EXISTS instances (
                                         id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                         name              varchar(255),
    type              varchar(255),                  -- REDIS | HAZELCAST
    host              varchar(255),
    port              integer NOT NULL,
    enabled           boolean NOT NULL,
    cluster_name      varchar(255),                  -- Hazelcast için zorunlu
    members           varchar(1000),                 -- "host:port,host:port"
    metrics_url       varchar(1000),                 -- jmx_exporter scrape adresleri
    username          varchar(255),                  -- Redis ACL kullanıcısı
    password_env_var  varchar(255),                   -- parolanın DEĞİL, değişken adının kendisi
    tls_enabled       boolean NOT NULL DEFAULT false -- Redis TLS bağlantısı
    );

-- ── İzleme kullanıcıları (JWT + BCrypt) ─────────────────────────────────────
CREATE TABLE IF NOT EXISTS users (
                                     id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                     username       varchar(255) NOT NULL,
    password_hash  varchar(255) NOT NULL,            -- BCrypt
    role           varchar(255),                     -- MONITOR | ADMIN
    email          varchar(255),
    active         boolean NOT NULL,
    created_at     bigint NOT NULL,                  -- epoch millis
    last_login_at  bigint NOT NULL,                  -- epoch millis
    CONSTRAINT uk_users_username UNIQUE (username)
    );

-- ── Metrik zaman serisi (30 sn'de bir, 7 gün retention) ─────────────────────
CREATE TABLE IF NOT EXISTS metric_snapshots (
                                                id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                                instance_id          bigint,
                                                collected_at         timestamp(6) without time zone,
    status               varchar(255),               -- UP | DOWN
    version              varchar(255),
    uptime_seconds       bigint NOT NULL,
    cpu_percent          double precision NOT NULL,
    memory_used          bigint NOT NULL,
    memory_max           bigint NOT NULL,
    key_count            bigint NOT NULL,
    client_count         integer NOT NULL,
    connection_errors    bigint NOT NULL,
    fragmentation_ratio  double precision NOT NULL,
    node_count           integer NOT NULL,
    partition_json       varchar(255),               -- Hazelcast partition dağılımı
    evicted_keys         bigint DEFAULT 0,
    expired_keys         bigint DEFAULT 0,
    ops_per_sec          bigint DEFAULT 0,
    hit_ratio            double precision,           -- null = hesaplanamadı
    replication_role     varchar(255),
    connected_replicas   integer DEFAULT 0,
    overall_status       varchar(255),
    CONSTRAINT metric_snapshots_overall_status_check
    CHECK (overall_status IN (
           'AVAILABLE', 'UNAVAILABLE', 'NOT_APPLICABLE', 'PERMISSION_DENIED',
           'TIMEOUT', 'STALE', 'ESTIMATED', 'NOT_READY'
                             ))
    );

-- ── Denetim kaydı (kimlik + mutasyon + key erişimi, 90 gün retention) ───────
CREATE TABLE IF NOT EXISTS audit_logs (
                                          id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                          action      varchar(64) NOT NULL,
    username    varchar(128),
    detail      varchar(1000),                       -- arama terimleri maskelidir
    result      varchar(32),
    ip_address  varchar(64),
    "timestamp" timestamp(6) without time zone NOT NULL
    );

CREATE INDEX IF NOT EXISTS idx_audit_timestamp ON audit_logs ("timestamp");
CREATE INDEX IF NOT EXISTS idx_audit_username  ON audit_logs (username);
CREATE INDEX IF NOT EXISTS idx_audit_action    ON audit_logs (action);
-- ── Alarm olayları (başlayan / düzelen, 90 gün retention, ADR-0015) ─────────
CREATE TABLE IF NOT EXISTS alert_events (
                                            id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                            rule_name       varchar(128) NOT NULL,
    instance_id     bigint,
    instance_name   varchar(255),
    severity        varchar(16),
    state           varchar(16) NOT NULL,                -- FIRING | RESOLVED
    observed_value  double precision,                    -- INSTANCE_DOWN'da null
    threshold       double precision,
    message         varchar(512),
    occurred_at     timestamp(6) without time zone NOT NULL,
    CONSTRAINT alert_events_state_check CHECK (state IN ('FIRING', 'RESOLVED'))
    );

CREATE INDEX IF NOT EXISTS idx_alert_events_instance_time ON alert_events (instance_id, occurred_at);
